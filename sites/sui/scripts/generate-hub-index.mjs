// Builds the data behind the documentation hub from the mirrored content trees.
//
//   node scripts/generate-hub-index.mjs
//
// Titles and descriptors come from each page's own frontmatter rather than being
// written here, so the hub says what the pages say. Re-run it after a mirror.
//
// Sui sections get site-relative URLs, which Docusaurus route-checks, so a
// section that disappears fails the build. The other sites get absolute URLs,
// which it cannot check -- those are verified by hand with curl and the trailing
// slash on move-book matters, because without it every link 301s.

import fs from "fs";
import path from "path";
import { createRequire } from "module";
const require_ = createRequire(import.meta.url);
const matter = require_("gray-matter");
const { REPO_ROOT } = require_("./lib/roots.cjs");

// Every site's pages, not just this one's: the hub indexes all of them.
const CONTENT = path.join(REPO_ROOT, "content");

const SITES = {
  sui: { base: "", depth: 2 },
  walrus: { base: "https://docs.wal.app", depth: 1 },
  "ts-sdks": { base: "https://sdk.mystenlabs.com", depth: 1 },
  "move-book": { base: "https://move-book.com", depth: 1, trailingSlash: true },
};

/** One line, not a paragraph: the hub lists ~70 of these. */
function descriptor(desc) {
  if (!desc) return "";
  // These are reflowed and cut at the first sentence, so they are not verbatim
  // quotes; normalise the dashes the source pages use to commas.
  let s = String(desc).replace(/\s+/g, " ").replace(/\s*[—–]\s*/g, ", ").trim();
  const stop = s.search(/\.\s|\.$/);
  if (stop > 0) s = s.slice(0, stop + 1);
  if (s.length > 104) s = s.slice(0, s.lastIndexOf(" ", 104)).replace(/[,;:]$/, "") + "…";
  return s;
}

/**
 * A section's frontmatter, or null if it should not be indexed.
 *
 * draft and unlisted are both skipped: Docusaurus builds no route at all for a
 * draft, so linking to one fails the strict build (which is how develop/security
 * was caught), and an unlisted page is deliberately kept off the sidebar, so
 * putting it on the hub would defeat that.
 */
function usable(fm) {
  return fm && fm.title && !fm.draft && !fm.unlisted ? fm : null;
}

function meta(dir) {
  for (const n of ["index.mdx", "index.md"]) {
    const p = path.join(dir, n);
    if (fs.existsSync(p)) {
      const fm = usable(matter(fs.readFileSync(p, "utf8")).data);
      if (fm) return fm;
    }
  }
  const sib = dir + ".mdx";
  if (fs.existsSync(sib)) {
    const fm = usable(matter(fs.readFileSync(sib, "utf8")).data);
    if (fm) return fm;
  }
  return null;
}

function sections(site) {
  const cfg = SITES[site];
  const root = path.join(CONTENT, site);
  if (!fs.existsSync(root)) return {};
  const skip = new Set(["images", "snippets"]);
  const groups = {};
  const tops = fs.readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !skip.has(d.name));
  for (const top of tops) {
    const dirs = cfg.depth === 2
      ? fs.readdirSync(path.join(root, top.name), { withFileTypes: true })
          .filter((d) => d.isDirectory() && !skip.has(d.name))
          .map((d) => [top.name, d.name])
      : [[top.name]];
    for (const parts of dirs) {
      const fm = meta(path.join(root, ...parts));
      if (!fm) continue;
      const rel = parts.join("/");
      const url = cfg.base
        ? `${cfg.base}/${rel}${cfg.trailingSlash ? "/" : ""}`
        : `/${rel}`;
      (groups[parts[0]] ||= []).push({
        name: fm.title,
        descriptor: descriptor(fm.description),
        url,
      });
    }
  }
  for (const k of Object.keys(groups)) groups[k].sort((a, b) => a.name.localeCompare(b.name));
  return groups;
}

const sui = sections("sui");
const all = {
  walrus: sections("walrus"),
  "ts-sdks": sections("ts-sdks"),
  "move-book": sections("move-book"),
};
const flat = (o) => Object.values(o).flat().sort((a, b) => a.name.localeCompare(b.name));

const index = {
  $comment:
    "Generated by scripts/generate-hub-index.mjs from the frontmatter of each mirrored section. " +
    "Do not hand-edit; re-run the script after a mirror. External URLs are verified by hand.",
  categories: [
    { name: "Getting started", items: sui["getting-started"] || [] },
    { name: "Build on Sui", items: sui["develop"] || [] },
    { name: "Onchain finance", items: sui["onchain-finance"] || [] },
    { name: "Sui Stack", items: sui["sui-stack"] || [] },
    { name: "Node operation", items: sui["operators"] || [] },
    { name: "References", items: sui["references"] || [] },
    { name: "Data storage with Walrus", items: flat(all.walrus) },
    { name: "SDKs", items: flat(all["ts-sdks"]) },
    { name: "The Move language", items: flat(all["move-book"]) },
  ].filter((c) => c.items.length),
};

const OUT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../src/data/hub-index.json");
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(index, null, 2) + "\n");

let n = 0;
for (const c of index.categories) {
  console.log(`  ${String(c.items.length).padStart(3)}  ${c.name}`);
  n += c.items.length;
}
console.log(`\n  ${n} sections across ${index.categories.length} categories`);
